-- ★ 4) 辅助查询
function WR_Forever_GetClassKit(classToken)
    if type(classToken) ~= "string" then return {} end
    local t = WR_Forever_ClassKit[classToken]
    if not t then return {} end
    local out = {}
    for k in pairs(t) do out[#out+1] = k end
    return out
end

-- 判断某技能是否属于某职业的无限技能集
function WR_Forever_IsInKit(classToken, name)
    if type(classToken) ~= "string" or type(name) ~= "string" then return false end
    local t = WR_Forever_ClassKit[classToken]
    return t and (t[name] == true)
end

