-- 把文本插入聊天框（实现"复制"效果）
local function InsertToChat(text)
    local editBox = ChatEdit_GetActiveWindow()
    if not editBox then
        editBox = ChatFrame1EditBox
        ChatEdit_ActivateChat(editBox)
    end
    if editBox then
        editBox:Insert(text)
        editBox:SetFocus()
    end
end

-- 从命令字符串提取变量名（如 "/CJ_TOUYAO on" -> "CJ_TOUYAO"）
local function ExtractVarName(cmd)
    local var = cmd:match("^/(%S+)")
    return var
end

-- 直接执行命令（右键 toggle）
local function ExecuteToggle(cmd)
    local var = ExtractVarName(cmd)
    if not var then return end
    -- 通用命令（如 /rl /pigchat）直接调用
    if SlashCmdList[var] then
        SlashCmdList[var]("toggle")
    else
        -- 可能是通用命令，尝试直接插入执行
        InsertToChat(cmd)
    end
end

