-- 更新专精下拉框选项（切换职业时调用）
function ZZ_CmdList_UpdateSpecDropdown()
    if not specDropdown then return end
    local classData = ZZ_CMDLIST_DATA[currentClassIndex]
    if not classData then return end

    UIDropDownMenu_Initialize(specDropdown, function(self, level)
        -- "全部专精"选项
        local info = UIDropDownMenu_CreateInfo()
        info.text = "全部专精"
        info.value = 0
        info.checked = (currentSpecIndex == 0)
        info.func = function(button)
            currentSpecIndex = button.value
            UIDropDownMenu_SetSelectedValue(specDropdown, button.value)
            ZZ_CmdList_RefreshRight()
        end
        UIDropDownMenu_AddButton(info, level)
        -- 各专精选项
        for i, spec in ipairs(classData.specs) do
            info = UIDropDownMenu_CreateInfo()
            info.text = spec.name
            info.value = i
            info.checked = (currentSpecIndex == i)
            info.func = function(button)
                currentSpecIndex = button.value
                UIDropDownMenu_SetSelectedValue(specDropdown, button.value)
                ZZ_CmdList_RefreshRight()
            end
            UIDropDownMenu_AddButton(info, level)
        end
    end)

    -- 设置当前显示文字（兼顾越界保护）
    if currentSpecIndex == 0 then
        UIDropDownMenu_SetText(specDropdown, "全部专精")
    else
        local spec = classData.specs[currentSpecIndex]
        if spec then
            UIDropDownMenu_SetText(specDropdown, spec.name)
        else
            currentSpecIndex = 0
            UIDropDownMenu_SetText(specDropdown, "全部专精")
        end
    end
    UIDropDownMenu_SetSelectedValue(specDropdown, currentSpecIndex)
end

-- 刷新右侧命令列表
function ZZ_CmdList_RefreshRight()
    if not MainFrame then return end
    local rightChild = MainFrame.rightChild
    -- 清除旧内容：删除之前创建的所有子控件
    if MainFrame.rightRows then
        for _, row in ipairs(MainFrame.rightRows) do
            row:Hide()
            row:SetParent(nil)
        end
    end
    MainFrame.rightRows = {}

    local classData = ZZ_CMDLIST_DATA[currentClassIndex]
    if not classData then return end

    local yPos = -4
    local rowHeight = 22
    local specGap = 6
    local btnWidth = 520

    -- 根据 currentSpecIndex 决定显示哪些专精
    local specsToShow
    if currentSpecIndex == 0 then
        specsToShow = classData.specs
    else
        specsToShow = { classData.specs[currentSpecIndex] }
    end

    for _, spec in ipairs(specsToShow) do
        -- 专精标题
        local specTitle = rightChild:CreateFontString(nil, "OVERLAY", "GameFontNormal")
        specTitle:SetPoint("TOPLEFT", rightChild, "TOPLEFT", 6, yPos)
        specTitle:SetText(classData.color .. "【" .. spec.name .. "】|r")
        specTitle:SetJustifyH("LEFT")
        table.insert(MainFrame.rightRows, specTitle)
        yPos = yPos - (rowHeight + 2)

        -- 命令行
        for _, item in ipairs(spec.items) do
            local cmd, desc, def = item[1], item[2], item[3]
            local row = CreateFrame("Button", nil, rightChild, "UIPanelButtonTemplate")
            row:SetSize(btnWidth, 20)
            row:SetPoint("TOPLEFT", rightChild, "TOPLEFT", 6, yPos)
            -- 允许左键和右键点击（模板默认只响应左键）
            row:RegisterForClicks("LeftButtonUp", "RightButtonUp")
            -- 命令文字（黄色）+ 说明（白色）+ 默认（绿/红）
            local defColor = def == "开" and "|cff00ff00" or (def == "关" and "|cffff6060" or "|cff888888")
            local btnText = "|cffffd700" .. cmd .. "|r  " .. desc .. "  " .. defColor .. "[" .. def .. "]|r"
            row:SetText(btnText)
            -- 用模板自带字体，左对齐并缩小字号以容纳完整文字
            local fs = row:GetFontString()
            if fs then
                fs:SetJustifyH("LEFT")
                fs:SetFont(STANDARD_TEXT_FONT, 11, "")
            end

            -- Tooltip
            row:SetScript("OnEnter", function(self)
                GameTooltip:SetOwner(self, "ANCHOR_TOPLEFT")
                GameTooltip:SetText("|cffffd700" .. cmd .. "|r")
                GameTooltip:AddLine(desc, 1, 1, 1, true)
                GameTooltip:AddLine("默认: " .. def, 0.8, 0.8, 0.8)
                GameTooltip:AddLine(" ")
                GameTooltip:AddLine("|cffffd700左键:|r 填入聊天框", 0.5, 1, 0.5)
                GameTooltip:AddLine("|cffffd700Shift+左键:|r 填入 /变量名 on", 0.5, 1, 0.5)
                GameTooltip:AddLine("|cffffd700Ctrl+左键:|r 填入 /变量名 off", 0.5, 1, 0.5)
                GameTooltip:AddLine("|cffffd700右键:|r 直接切换开关", 0.5, 1, 0.5)
                GameTooltip:Show()
            end)
            row:SetScript("OnLeave", function() GameTooltip:Hide() end)

            -- 点击处理
            row.cmd = cmd
            row:SetScript("OnClick", function(self, button)
                local isShift = IsShiftKeyDown()
                local isCtrl = IsControlKeyDown()
                if button == "LeftButton" then
                    local var = ExtractVarName(self.cmd)
                    if isShift and var then
                        InsertToChat("/" .. var .. " on")
                    elseif isCtrl and var then
                        InsertToChat("/" .. var .. " off")
                    else
                        InsertToChat(self.cmd)
                    end
                elseif button == "RightButton" then
                    ExecuteToggle(self.cmd)
                end
            end)

            table.insert(MainFrame.rightRows, row)
            yPos = yPos - rowHeight
        end
        yPos = yPos - specGap
    end

    rightChild:SetHeight(-yPos + 10)
end

-- 打开/关闭界面
function ZZ_CmdList_Toggle()
    local frame = CreateMainFrame()
    if frame:IsShown() then
        frame:Hide()
    else
        -- ★ 2026-08-21：打开命令清单默认选中「通用」分类，直接展示通用命令清单内容
        local generalIdx = 1
        for i, cd in ipairs(ZZ_CMDLIST_DATA) do
            if cd.name == "通用" then generalIdx = i; break end
        end
        currentClassIndex = generalIdx
        currentSpecIndex = 0
        ZZ_CmdList_UpdateSpecDropdown()
        ZZ_CmdList_RefreshRight()
        -- 高亮当前职业按钮
        for _, b in ipairs(frame.leftButtons) do
            b:UnlockHighlight()
        end
        if frame.leftButtons[currentClassIndex] then
            frame.leftButtons[currentClassIndex]:LockHighlight()
        end
        frame:Show()
    end
end

